"""Collect candidates for the clean-contour cards in a repository.

    python3 -I tools/search.py <repo> [--lang py,ts,kt,go,cs] [--cards C4,C11]
    python3 -I tools/search.py --selftest

Columns: card, file:line, the line of code. A hit is a candidate, not a verdict:
each one is read against the card's questions. The signs live in
`skills/clean-contour-check/signs.json`; the language is taken from the file
extension. Tests, migrations, generated and vendored code are skipped per
language, as the skill's "Languages" paragraph says.
"""
import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIGNS_PATH = HERE.parent / "skills" / "clean-contour-check" / "signs.json"

ALL_LANGS = ("py", "ts", "kt", "go", "cs")


def load_signs() -> dict:
    with open(SIGNS_PATH, encoding="utf-8") as f:
        return json.load(f)


def compile_card(card: dict) -> list:
    """Compile a card's list of regexes; a {"manual": ...} entry compiles to None."""
    out = []
    for item in card:
        if isinstance(item, dict) and "manual" in item:
            out.append(None)
        else:
            out.append(re.compile(item))
    return out


def skip_regex(signs: dict, lang: str):
    return re.compile("|".join(f"(?:{p})" for p in signs["skip"][lang]))


def walk_files(root: Path, extensions: list, skip_rx) -> list:
    files = []
    for ext in extensions:
        for p in root.rglob(f"*{ext}"):
            if skip_rx.search(str(p)):
                continue
            files.append(p)
    return sorted(files)


def hits_for(root: Path, signs: dict, langs: list, cards: list) -> list:
    rootp = Path(root)
    hits = []
    for card_name in cards:
        card = signs["cards"][card_name]
        for lang in langs:
            pats = compile_card(card.get(lang, []))
            if not pats:
                continue
            skip_rx = skip_regex(signs, lang)
            files = walk_files(rootp, signs["extensions"][lang], skip_rx)
            for f in files:
                try:
                    lines = f.read_text(encoding="utf-8", errors="replace").splitlines()
                except OSError:
                    continue
                if any("<auto-generated" in ln for ln in lines[:15]):
                    continue
                for n, line in enumerate(lines, 1):
                    stripped = line.lstrip()
                    if stripped.startswith("//") or stripped.startswith("#"):
                        continue
                    if any(r is not None and r.search(line) for r in pats):
                        hits.append((card_name, str(f.relative_to(rootp)), n, line.strip()[:140]))
    return sorted(hits, key=lambda h: (h[0], h[1], h[2]))


def selftest() -> int:
    signs = load_signs()
    failures = []

    # Every regex compiles.
    for card_name, card in signs["cards"].items():
        for lang, pats in card.items():
            for item in pats:
                if isinstance(item, dict) and "manual" in item:
                    continue
                try:
                    re.compile(item)
                except re.error as e:
                    failures.append(f"{card_name}/{lang}: bad regex {item!r}: {e}")

    # Every card C1..C17 appears.
    for i in range(1, 18):
        name = f"C{i}"
        if name not in signs["cards"]:
            failures.append(f"missing card {name}")

    # Fixtures: each pattern must hit its fixture line, skip list drops a test file.
    fixtures_root = HERE / "fixtures"
    for lang in ALL_LANGS:
        lang_dir = fixtures_root / lang
        if not lang_dir.is_dir():
            failures.append(f"missing fixture dir {lang_dir}")
            continue
        skip_rx = skip_regex(signs, lang)
        # Collect the non-skipped fixture files (the "must hit" files).
        fixture_files = []
        for f in sorted(lang_dir.iterdir()):
            if f.is_dir():
                continue
            if skip_rx.search(str(f)):
                continue
            fixture_files.append(f)
        if not fixture_files:
            failures.append(f"{lang}: no non-skipped fixture file")
            continue
        # Read all fixture lines once.
        all_lines = []
        for f in fixture_files:
            try:
                all_lines.extend(f.read_text(encoding="utf-8", errors="replace").splitlines())
            except OSError:
                continue
        # Each pattern must hit at least one fixture line.
        for card_name, card in signs["cards"].items():
            for item in card.get(lang, []):
                if isinstance(item, dict) and "manual" in item:
                    continue
                rx = re.compile(item)
                if not any(rx.search(line) for line in all_lines):
                    failures.append(f"{lang}/{card_name}: pattern {item!r} hits no fixture line")
        # The skip list must drop a test file: a file whose name says "test"
        # must be skipped, and at least one such file must exist.
        test_files = [f for f in sorted(lang_dir.iterdir())
                      if f.is_file() and ("test" in f.name.lower() or ".spec." in f.name)]
        if not test_files:
            failures.append(f"{lang}: no test file present to check the skip list")
        for f in test_files:
            if not skip_rx.search(str(f)):
                failures.append(f"{lang}: test file {f.name} not dropped by skip list")

    # The search itself, over the fixtures directory: every language gives hits,
    # and no hit comes from a test file.
    found = hits_for(fixtures_root, signs, list(ALL_LANGS), list(signs["cards"]))
    for lang in ALL_LANGS:
        if not any(rel.startswith(f"{lang}/") for _, rel, _, _ in found):
            failures.append(f"{lang}: the search over fixtures found nothing")
    for _, rel, _, _ in found:
        name = Path(rel).name
        if "test" in name.lower() or ".spec." in name:
            failures.append(f"a hit in a test file: {rel}")

    if failures:
        for msg in failures:
            print(f"SELFTEST FAIL: {msg}", file=sys.stderr)
        return 1
    print("selftest ok")
    return 0


def main(argv: list) -> int:
    if "--selftest" in argv:
        return selftest()

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repo")
    parser.add_argument("--lang", default=",".join(ALL_LANGS))
    parser.add_argument("--cards", default=None)
    args = parser.parse_args(argv)

    signs = load_signs()
    langs = [l for l in args.lang.split(",") if l]
    if args.cards:
        cards = [c for c in args.cards.split(",") if c]
    else:
        cards = list(signs["cards"].keys())
    for card_name, rel, n, text in hits_for(Path(args.repo), signs, langs, cards):
        print(f"{card_name}\t{rel}:{n}\t{text}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
